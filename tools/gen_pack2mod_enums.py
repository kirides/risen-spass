#!/usr/bin/env python3
"""Writes src/pack2mod/enums_data.inc: the engine's enum names (number -> name) that risen-pack2mod needs to turn the numbers stored in
templates into the names `risen.template.patch` takes. The names come from the engine's reflection (tools/extmod_enums.py joins the mods/itemdump
log with the numbers in the game's own archives -> tools/extmod_enums.json) plus the values confirmed in docs/RE.md section 43 / ITEM_PROPERTIES.md.

    python -I tools/gen_pack2mod_enums.py            (regenerates the .inc from tools/extmod_enums.json; commit both)

The data is game data only (names of the engine's enums), not the content of any mod.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SKILLS = ["HitPoints", "ManaPoints", "Level", "Experience", "LearnPoints", "MaxHitPoints", "MaxManaPoints", "Strength", "Dexterity",
          "Intelligence", "ProtEdge", "ProtBlunt", "ProtPoint", "ProtFire", "ProtIce", "ProtMagic", "Sword", "Axe", "Staff", "Bow",
          "CrossBow", "Circle", "Fireball", "Frost", "Missile", "Smith", None, None, "Pickpocket", "Sneak", "Acrobat", "Alchemy",
          "Scribe", "Trophy"]
ENUMS = {
    "gEItemUseType": {0: "None", 1: "1H", 2: "2H", 3: "BS", 4: "Arrow", 5: "Bow", 6: "CrossBow", 7: "Bolt", 9: "Shield", 10: "Armor", 11: "Helmet",
                      12: "Staff", 13: "Amulet", 14: "Ring", 18: "Axe", 19: "Cast"},
    "gEDamageType": {0: "None", 1: "Edge", 2: "Blunt", 3: "Point", 4: "Fire", 5: "Ice", 6: "Magic"},
    "gEItemCategory": {0: "None", 1: "Weapon", 2: "Armor", 3: "Consumable", 5: "Magic", 6: "Misc", 7: "Written"},
    "gEInteractionUseType": {0: "None", 1: "Item"},
}
j = json.load(open(os.path.join(HERE, "extmod_enums.json"), encoding="utf8"))
enums = {k: dict(v) for k, v in ENUMS.items()}
for k, v in j.get("enums", {}).items():
    enums.setdefault(k, {}).update({int(n): s for n, s in v.items()})
skills = {i: s for i, s in enumerate(SKILLS) if s}
for n, s in (j.get("skills") or {}).items():
    skills[int(n)] = s
out = ["// generated by tools/gen_pack2mod_enums.py from tools/extmod_enums.json: do not edit", "// {enum type, value, name}"]
out.append("static const EnumRow kEnumRows[] = {")
for t in sorted(enums):
    for n in sorted(enums[t]):
        out.append('    {"%s", %d, "%s"},' % (t, n, enums[t][n]))
out.append("};")
out.append("// {gESkill number, short name used by risen.balance}")
out.append("static const SkillRow kSkillRows[] = {")
for n in sorted(skills):
    out.append('    {%d, "%s"},' % (n, skills[n]))
out.append("};")
with open(os.path.join(HERE, "..", "src", "pack2mod", "enums_data.inc"), "w", encoding="utf8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(sum(len(v) for v in enums.values()), "enum values,", len(skills), "skills")
