"""Generate the .def files for a forwarding proxy DLL from the original DLL's export table.

Usage: gen_proxy_def.py <original.dll> <forward_module> <out_forward.def> <out_import.def>

Example:
    gen_proxy_def.py ...\\bin\\sentry.dll sentry_orig src/proxy/sentry_proxy.def src/proxy/sentry_orig.def

* <out_forward.def>  is linked into the proxy (sentry.dll): `sentry_init = sentry_orig.sentry_init`.
* <out_import.def>   is turned into sentry_orig.lib by `lib /DEF:` (CMake does this). MSVC's linker only
                     accepts `module.name` forwarders when it can find an import library for `module`,
                     otherwise it reports LNK2001 for every forwarded name.
"""
import pathlib
import sys

import pefile


def main() -> None:
    src, target = sys.argv[1], sys.argv[2]
    out_fwd, out_imp = pathlib.Path(sys.argv[3]), pathlib.Path(sys.argv[4])
    library = pathlib.Path(src).stem
    pe = pefile.PE(src, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    symbols = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda s: s.ordinal)

    header = f"; Generated by tools/gen_proxy_def.py from {pathlib.Path(src).name} - do not edit."
    fwd = [header, f"LIBRARY {library}", "EXPORTS"]
    imp = [header, f"LIBRARY {target}", "EXPORTS"]
    for s in symbols:
        if not s.name:
            raise SystemExit(f"ordinal-only export #{s.ordinal} is not supported")
        name = s.name.decode()
        fwd.append(f"    {name} = {target}.{name}")
        imp.append(f"    {name}")

    for path, lines in ((out_fwd, fwd), (out_imp, imp)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="ascii")
        print(f"wrote {path} ({len(lines) - 3} exports)")


if __name__ == "__main__":
    main()
