"""Generates src/modkit/core/dialog_commands.inc (the dialogue commands and their parameters for risen-modkit's dialogue editor) from the
"Dialogue commands" section of docs/PROPERTIES.md, which is itself generated from the engine's reflection. Run after that doc changed:

    python -I tools/gen_modkit_commands.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    doc = open(os.path.join(ROOT, "docs", "PROPERTIES.md"), encoding="utf-8").read()
    start = doc.index("## Dialogue commands")
    end = doc.find("\n## ", start + 5)
    sec = doc[start:end if end > 0 else len(doc)]
    commands = []
    for m in re.finditer(r"^### (.+?)\n(.*?)(?=^### |\Z)", sec, re.M | re.S):
        name = m.group(1).strip()
        if name.startswith("("):
            continue  # the base class: Speaker, Listener, Text, Gesture of every command
        params = re.findall(r"^\| `(\w+)` \| `([^`]+)` \|", m.group(2), re.M)
        commands.append((name, params))
    out = ["// generated by tools/gen_modkit_commands.py from docs/PROPERTIES.md (\"Dialogue commands\"): do not edit",
           "// {command, {{parameter, engine type}, ...}}"]
    out.append("static const CommandRow kCommandRows[] = {")
    for name, params in commands:
        ps = ", ".join('{"%s", "%s"}' % (p, t) for p, t in params)
        out.append('    {"%s", {%s}},' % (name, ps))
    out.append("};")
    path = os.path.join(ROOT, "src", "modkit", "core", "dialog_commands.inc")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"{len(commands)} commands -> {path}")


if __name__ == "__main__":
    sys.exit(main())
