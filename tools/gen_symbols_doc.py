#!/usr/bin/env python3
"""Generates docs/SYMBOLS.md from src/game/symbols.h.

    python tools/gen_symbols_doc.py > docs/SYMBOLS.md

For every engine function the layer binds: field name, module, demangled signature, RVA and whether it is required.
RVA and the readable signature come from the export dumps (%TEMP%\\risen_re\\<Dll>.exports.txt / .demangled.txt, made by
tools/dump_exports.py and tools/demangle_exports.py); without them those columns show "-".
"""
import os
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
header = (root / 'src' / 'game' / 'symbols.h').read_text(encoding='utf-8')
dump_dir = Path(os.environ.get('TEMP', '/tmp')) / 'risen_re'

# X(field, L"Module.dll", "?decorated@name", type, required)
pattern = re.compile(r'X\((\w+),\s*L"([\w.]+)",\s*"([^"]+)",\s*(.+?),\s*(true|false)\)\s*\\?\s*$', re.M)
rows = [(m.group(1), m.group(2), m.group(3), m.group(5) == 'true') for m in pattern.finditer(header)]


def load(module, kind):
    p = dump_dir / f'{Path(module).stem}.{kind}.txt'
    out = {}
    if p.exists():
        for line in p.read_text(encoding='utf-8', errors='replace').splitlines():
            parts = line.split(None, 2)
            if len(parts) == 3 and re.fullmatch(r'[0-9a-fA-F]{6,8}', parts[0]):
                out.setdefault(parts[0].lower(), parts[2] if kind == 'demangled' else parts[2])
    return out


exports = {}
demangled = {}
for module in {r[1] for r in rows}:
    exports[module] = {}
    for line in (dump_dir / f'{Path(module).stem}.exports.txt').read_text(encoding='utf-8', errors='replace').splitlines() \
            if (dump_dir / f'{Path(module).stem}.exports.txt').exists() else []:
        parts = line.split()
        if len(parts) >= 3 and re.fullmatch(r'[0-9a-fA-F]{6,8}', parts[0]):
            exports[module][parts[2]] = parts[0].lower()
    demangled[module] = load(module, 'demangled')

out = []
out.append('# Engine symbols')
out.append('')
out.append('Generated by `tools/gen_symbols_doc.py` from `src/game/symbols.h`. Every engine function the Lua layer calls or hooks is bound by its')
out.append('decorated export name (`GetProcAddress`), so nothing depends on addresses; the RVA column is informational (this game build,')
out.append('see `risen.engine.build()`). **Required** symbols must resolve or the layer stays off; for an optional one only its own feature is')
out.append('disabled (`risen.engine.missing()` lists what failed). To add one: see the developer guide in `docs/DEVELOPMENT.md`.')
out.append('')
out.append(f'{len(rows)} symbols, {sum(1 for r in rows if r[3])} required.')
out.append('')
current = None
for field, module, name, required in sorted(rows, key=lambda r: (r[1], r[0])):
    if module != current:
        current = module
        out.append(f'## {module}')
        out.append('')
        out.append('| Field | Function | RVA | Required |')
        out.append('|---|---|---|---|')
    rva = exports.get(module, {}).get(name)
    readable = demangled.get(module, {}).get(rva, name) if rva else name
    readable = readable.replace('|', '\\|')
    out.append(f'| `{field}` | `{readable}` | {("0x" + rva.lstrip("0")) if rva else "-"} | {"yes" if required else "no"} |')
    if False:
        pass
out.append('')
sys.stdout.write('\n'.join(out))
