#!/usr/bin/env python3
"""habitats.lua for mods/example_random_encounters from the output of tools/world_monsters.py.

    python tools/world_monsters.py <data/common> monsters.json
    python tools/gen_habitats.py monsters.json mods/example_random_encounters/habitats.lua

Keeps outdoor monsters only (no test levels, dungeons, demo / final battle layers) and the layers that are on from the start or that a chapter
switches on (the "...Chapter2_MonsterRefill_Off" layers carry a chapter number: that is the first chapter in which the monster lives there).
Layers that only a story event switches on ("_Off" without a chapter) are left out.
"""
import collections
import json
import re
import sys


def chapter_of(layer):
    m = re.search(r"Chapter(\d)|Ch(\d)", layer)
    if m:
        return int(m.group(1) or m.group(2))
    return None if layer.endswith("_Off") else 1


def main(argv):
    rows = json.load(open(argv[1]))
    by = collections.defaultdict(list)
    for a in rows:
        if "Testlevel" in a["folder"] or "Dungeon" in a["folder"] or "Dungeon" in a["layer"] or a["layer"] in ("Final_Battle", "OutMain_Demo"):
            continue
        ch = chapter_of(a["layer"])
        if ch is None:
            continue
        parts = a["folder"].split("/")
        region = parts[2] if len(parts) > 2 else parts[-1]
        by[a["template"]].append((a["x"], a["y"], a["z"], region, ch))
    out = ["-- GENERATED by tools/gen_habitats.py from the game's world layers (tools/world_monsters.py): where the game itself places each monster.",
           "-- { x, y, z, region, first_chapter } per template; `region` is the game's own outdoor region (the folder of its world files). Do not edit: regenerate.",
           "return {"]
    for t in sorted(by):
        out.append("    %s = {" % t)
        for x, y, z, r, ch in sorted(set(by[t])):
            out.append('        { %d, %d, %d, "%s"%s },' % (x, y, z, r, "" if ch == 1 else ", %d" % ch))
        out.append("    },")
    out.append("}")
    open(argv[2], "w", newline="\n").write("\n".join(out) + "\n")
    print("%d templates, %d points" % (len(by), sum(len(v) for v in by.values())))


if __name__ == "__main__":
    main(sys.argv)
