out += ['', '| Projectile template | DamageAmount | DamageType | StartVelocity | SweepTestRadius (sweep test) | OnHitScript | DamageScript | Effect |', '|---|---|---|---|---|---|---|---|']
for name, _ in PROJECTILE_SPELLS:
    for t in projectiles_of[name]:
        if t in sets_of:
            out.append(f'| `{t}` | {num(t, "gCDamage_PS", "DamageAmount")} | {v(t, "gCDamage_PS", "DamageType")} | {num(t, "gCProjectile2_PS", "StartVelocity")} | '
                       f'{num(t, "gCProjectile2_PS", "SweepTestRadius")} ({v(t, "gCProjectile2_PS", "EnableSweepTest")}) | `{v(t, "gCProjectile2_PS", "OnHitScript")}` | '
                       f'`{v(t, "gCDamage_PS", "DamageScript")}` | `{v(t, "gCEffect_PS", "Effect")}` |')
