# ---- rune spells ------------------------------------------------------------------------------------------------------------------------
out += ['## Rune spells', '',
        'Rune = permanent (`ConsumeItem` False), scroll and orb = used up. Costs are `ManaCost`; the rune\'s `Requires` is the Circle level.', '',
        '| Spell | Rune: cost, requires, gold | Scroll: cost, gold | Orb: cost | CastItem / CastFail | StartTask / FocusMode |', '|---|---|---|---|---|---|']
for name in RUNES:
    r, s, o = f'It_Ru_{name}', f'It_Scr_{name}', f'It_Orb_{name}'
    if r not in sets_of:
        continue
    scroll = f'{v(s, "gCCastInfo_PS", "ManaCost")}, {v(s, "gCItem_PS", "GoldValue")}' if s in sets_of else '-'
    orb = v(o, 'gCCastInfo_PS', 'ManaCost') if o in sets_of else '-'
    out.append(f'| {name} | {v(r, "gCCastInfo_PS", "ManaCost")}, {req(r)}, {v(r, "gCItem_PS", "GoldValue")} | {scroll} | {orb} | '
               f'`{v(r, "gCCastInfo_PS", "CastItem")}` / `{v(r, "gCCastInfo_PS", "CastFail")}` | `{v(r, "gCCastInfo_PS", "StartTask")}` / `{v(r, "gCCastInfo_PS", "FocusMode")}` |')
out.append('')
teleports = [t for t in templates if t.startswith('It_Ru_Teleport')]
if teleports:
    out += ['### Teleport runes', '',
            'Free (`ManaCost` 0) runes whose `gCCastInfo_PS.CastInfo` names the teleporter script target: ' + ', '.join(f'`{t}` ({v(t, "gCCastInfo_PS", "CastInfo")})' for t in teleports) + '.', '']

# ---- property sets ----------------------------------------------------------------------------------------------------------------------
PURPOSE = {
    'gCCastInfo_PS': 'Runes, scrolls, orbs, crystals: mana cost, what is held, cast and what a failure shows.',
    'gCProjectile2_PS': 'Projectiles: speed, flight path, sweep test, hit and shoot scripts.',
    'gCDamage_PS': 'Damage of projectiles and weapons (`DamageAmount`, `DamageBonus`, `DamageMultiplier`, `DamageType`, `DamageScript`).',
    'gCEffect_PS': 'Visual/sound effect of the item in the hand and in flight.',
    'gCItem_PS': 'The item itself: gold value, use type, equip scripts, the skill arrays.',
}
out += ['## Property sets of the spell items', '']
for st in ('gCCastInfo_PS', 'gCProjectile2_PS', 'gCDamage_PS', 'gCEffect_PS', 'gCItem_PS'):
    if st not in props:
        continue
    n = sum(1 for t in templates if st in sets_of[t])
    out += [f'### {st}', '', f'{n} templates of this dump. {PURPOSE[st]}', '', '| Property | Type | Templates | Values seen |', '|---|---|---|---|']
    for name, entry in props[st].items():
        out.append(f'| `{name}` | `{entry["type"]}` | {len(entry["templates"])} | {summary(entry)} |')
    out.append('')

other = sorted(s for s in props if s not in PURPOSE and s != 'gCInteraction_PS')
if other:
    out += ['Visual / physics / interaction sets on these items (no influence on the numbers): ' + ', '.join(f'`{s}`' for s in other + ['gCInteraction_PS']) + '.', '']

# ---- carriers ---------------------------------------------------------------------------------------------------------------------------
out += ['## Who carries spell items', '']
