        '* **The item you hold** carries a `gCCastInfo_PS`: `ManaCost`, `ConsumeItem` (scrolls and orbs are used up), the cast item shown in the hand (`CastItem`, `It_Cast_*`), the ammo shown while aiming (`CastAmmo`, `It_MagicAmmo_*`), '
