#!/usr/bin/env python3
"""Builds docs/SPELL_PROPERTIES.md from a spass.log written by mods/spelldump (every item template that makes up a spell: crystals, runes, scrolls,
orbs, cast items, magic ammo, projectiles and their effects, with all property values, plus the RequiredSkills arrays).

    scripts/test-run.ps1 -Mods spelldump -Seconds 150 -NoAutostart
    python tools/gen_spell_properties_doc.py <test copy>/bin/spass/spass.log > docs/SPELL_PROPERTIES.md

"SPELL <template> <set> <prop>:<type>=<value>", "SARR <template> required|modifiers <skill> <amount> [<mode>]" and "CASTER <npc> <item> <amount>" lines are
aggregated; the hand-written parts (how a spell works, the numbers that are fixed in the game's scripts) are the findings of docs/RE.md section 29.
"""
import re
import sys
from collections import Counter, OrderedDict, defaultdict

log_path = sys.argv[1]

FRIENDLY = {
    'Magic_Missile': 'Missile', 'Magic_Frost': 'Frost', 'Magic_Fireball': 'Fireball', 'Magic_Circle': 'Circle', 'Stat_STR': 'Strength', 'Stat_DEX': 'Dexterity',
    'Stat_INT': 'Intelligence', 'Misc_Scribe': 'Scribe', 'Misc_Alchemy': 'Alchemy',
}

spell_re = re.compile(r'SPELL (\S+) (\S+) (\w+):(.+?)=(.*)$')
sarr_re = re.compile(r'SARR (\S+) (required|modifiers) (gESkill_\w+) (-?\d+)(?: (gESkillModifier_\w+))?$')
caster_re = re.compile(r'CASTER (\S+) (\S+) (\d+)$')

props = defaultdict(OrderedDict)     # set -> prop -> {'type', 'values': Counter, 'templates': set}
sets_of = defaultdict(set)
values = {}
required = defaultdict(list)
modifiers = defaultdict(list)
casters = []

for line in open(log_path, encoding='utf-8', errors='replace'):
    for tag, rx in (('SPELL', spell_re), ('SARR', sarr_re), ('CASTER', caster_re)):
        i = line.find(' ' + tag + ' ')
        if i < 0:
            continue
        m = rx.match(line[i + 1:].rstrip())
        if not m:
            continue
        if tag == 'SPELL':
            tpl, st, prop, typ, val = m.groups()
            p = props[st].setdefault(prop, {'type': typ, 'values': Counter(), 'templates': set()})
            p['values'][val] += 1
            p['templates'].add(tpl)
            sets_of[tpl].add(st)
            values[(tpl, st, prop)] = val
        elif tag == 'SARR':
            tpl, kind, skill, amount, mode = m.groups()
            name = skill[len('gESkill_'):]
            (required if kind == 'required' else modifiers)[tpl].append((FRIENDLY.get(name, name), int(amount), (mode or '')[len('gESkillModifier_'):]))
        else:
            casters.append(m.groups())
        break

templates = sorted(sets_of)


def v(t, st, prop, default=''):
    x = values.get((t, st, prop))
    if x is None:
        return default
    return x.replace('gEDamageType_', '').replace('gEItemUseType_', '').replace('�', '?')


def req(t):
    r = required.get(t)
    return ', '.join(f'{s} {a}' for s, a, _ in r) if r else '-'


def num(t, st, prop):
    x = values.get((t, st, prop))
    try:
        return f'{float(x):g}'
    except (TypeError, ValueError):
        return '?'


def summary(entry):
    typ, vals = entry['type'], entry['values']
    if re.fullmatch(r'(long|int|float|unsigned long|short|ulong)', typ):
        nums = []
        for val in vals:
            try:
                nums.append(float(re.sub(r'[^0-9eE+.\-]', '', val)))
            except ValueError:
                pass
        if nums:
            lo, hi = min(nums), max(nums)
            fmt = (lambda x: str(int(x))) if all(x == int(x) for x in nums) else (lambda x: f'{x:g}')
            return f'{fmt(lo)} .. {fmt(hi)} ({len(vals)} distinct)'
    if typ.startswith('bTPropertyContainer<enum') or typ == 'bool':
        top = vals.most_common(6)
        return ', '.join(f'`{x}` x{c}' for x, c in top) + (f', ... ({len(vals)} distinct)' if len(vals) > 6 else '')
    top = [x for x, _ in vals.most_common(3)]
    shown = ', '.join('`' + (x if len(x) < 40 else x[:37] + '...') + '`' if x else '(empty)' for x in top)
    return shown + (f', ... ({len(vals)} distinct)' if len(vals) > 3 else '')


PROJECTILE_SPELLS = [('Fireball', 'It_Crystal_Fire'), ('Frost', 'It_Crystal_Frost'), ('Missile', 'It_Crystal_Magic')]
RUNES = ['Beast', 'Berserker', 'BlueBarrier', 'EnhancedHeal', 'Illusion', 'Inferno', 'Joke', 'Levitate', 'Light', 'MediumHeal', 'MinorHeal', 'Nautilus', 'OpenLock',
         'Protection', 'RedBarrier', 'Skeleton', 'Speed', 'Telekinesis']
projectiles_of = {'Fireball': [f'It_Projectile_Fireball_S{i}' for i in range(3)], 'Frost': [f'It_Projectile_Frost_S{i}' for i in range(3)], 'Missile': ['It_Projectile_Missile_S0']}

