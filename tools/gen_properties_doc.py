#!/usr/bin/env python3
"""Builds docs/PROPERTIES.md (and optionally the Lua command table) from a spass.log written by mods/propdump.

    scripts/test-run.ps1 -Mods propdump -Seconds 130
    python tools/gen_properties_doc.py <test copy>/bin/spass/spass.log > docs/PROPERTIES.md
    python tools/gen_properties_doc.py <log> --lua-commands      # the COMMAND_PROPS table used by risen.dialog.create

Every "PROP <object> <name>:<type> ..." line becomes a table. Types are the engine's own type names.
"""
import re
import sys
from collections import OrderedDict

log = open(sys.argv[1], encoding='utf-8', errors='replace').read().splitlines()
entity_sets, commands, others = OrderedDict(), OrderedDict(), OrderedDict()

for line in log:
    i = line.find(' PROP ')
    if i < 0:
        continue
    body = line[i + 6:].rstrip()
    if body.endswith('<unavailable>'):
        continue
    # the label ends where the first "Name:Type" token begins
    m = re.search(r'\s(\w+):\S', ' ' + body)
    label = body[:m.start()].strip() if m else body.strip()
    rest = body[len(label):].strip() if m else ''
    props = []
    for name, typ in re.findall(r'(\w+):(.+?)(?= \w+:|$)', rest):
        props.append((name, typ.strip()))
    if label.startswith('entity-set '):
        key = re.sub(r'\s*\((npc|item|player)\)$', '', label.split(' ', 1)[1])
        entity_sets.setdefault(key, props)
    elif label.startswith('command '):
        commands[label.split(' ', 1)[1]] = props
    elif label == 'command':
        commands['(base class of all commands)'] = props
    else:
        others[label] = props

if '--lua-commands' in sys.argv:
    # Lua table: command name -> { PropertyName = type kind }
    out = ['local COMMAND_PROPS = {']
    for name, props in commands.items():
        if name.startswith('('):
            continue
        fields = ', '.join(f'{n} = true' for n, t in props if n != 'Text' and not t.startswith('gCInfoLocString'))
        out.append(f'    {name} = {{ {fields} }},')
    out.append('}')
    print('\n'.join(out))
    sys.exit(0)

out = ['# Engine properties', '',
       'Generated by `tools/gen_properties_doc.py` from the engine\'s own reflection (`mods/propdump`). Property names and types are what '
       '`Entity:get_property/set_property`, `Quest`/`Info` `get_property/set_property` and `Info:*_command_property` accept; values use the engine\'s '
       'text format (enums as value names such as `gEGuild_Pir`, numbers and booleans as text, strings as-is). Use `list_properties` in the game '
       'to see the same list for any object.', '']

def table(props):
    rows = ['| Property | Type |', '|---|---|']
    for n, t in props:
        rows.append(f'| `{n}` | `{t.replace("|", "\\|")}` |')
    return rows + ['']

out += ['## Entity property sets', '',
        'Use the engine class name as `set`: `entity:get_property("gCNPC_PS", "Guild")`. A set is only available on entities that have it '
        '(`nil` otherwise); a set with no properties of its own is omitted.', '']
for name, props in entity_sets.items():
    if props:
        out += [f'### {name}', ''] + table(props)
out += ['## Quests and infos', '']
for name, props in others.items():
    out += [f'### {name}', ''] + table(props)
out += ['## Dialogue commands', '',
        'Parameters of the commands that can be added with `info:add_command(name)`; set them with `info:set_command_property(index, name, value)` or as '
        'extra fields of a `command` line in `risen.dialog.create` (`{ command = "GiveXP", Amount = 50 }`). Texts (`gCInfoLocString`) are set with '
        '`info:set_command_text` / the `text` field.', '']
for name, props in commands.items():
    out += [f'### {name}', ''] + (table(props) if props else ['(no parameters)', ''])
sys.stdout.write('\n'.join(out))
