#!/usr/bin/env python3
"""Builds docs/TEMPLATES.md from a spass.log written by mods/templatedump.

    scripts/test-run.ps1 -Mods templatedump -NoAutostart -Seconds 70
    python tools/gen_templates_doc.py <Risen test copy>/bin/spass/spass.log > docs/TEMPLATES.md

Every line "TPL <group>/<name>[ ?]" becomes an entry; "?" marks names the engine's Template(name) does not recognise.
"""
import re
import sys
from collections import defaultdict

lines = open(sys.argv[1], encoding='utf-8', errors='replace').read().splitlines()
groups = defaultdict(list)
unknown = []
for ln in lines:
    m = re.search(r'\bTPL (.+?)/([^/ ]+)( \?)?$', ln)
    if not m:
        continue
    group, name, bad = m.group(1), m.group(2), bool(m.group(3))
    groups[group].append(name)
    if bad:
        unknown.append(f'{group}/{name}')

total = sum(len(v) for v in groups.values())
out = []
out.append('# Entity templates')
out.append('')
out.append('Generated by `tools/gen_templates_doc.py` from the game\'s packed data (`data/common/templates/**/*.tple`, listed with '
           '`risen.template.list()`; see `mods/templatedump`). A template name is the file name without `.tple`; pass it to '
           '`risen.entity.spawn`, `risen.npc.spawn` or `risen.item.give`. '
           f'{total} templates in {len(groups)} directories.')
out.append('')
out.append('| Directory | Count |')
out.append('|---|---|')
for g in sorted(groups):
    out.append(f'| [{g}](#{re.sub(r"[^a-z0-9]+", "-", g.lower()).strip("-")}) | {len(groups[g])} |')
out.append('')
for g in sorted(groups):
    out.append(f'## {g}')
    out.append('')
    out.append(', '.join(f'`{n}`' for n in sorted(groups[g], key=str.lower)))
    out.append('')
if unknown:
    out.append('## Names the engine does not recognise')
    out.append('')
    out.append('`risen.template.exists` returns false for these (usually helper templates that are only used inside the editor or that '
               'need a different spelling):')
    out.append('')
    out.append(', '.join(f'`{u}`' for u in sorted(unknown, key=str.lower)))
    out.append('')
sys.stdout.write('\n'.join(out))
