<#
.SYNOPSIS
    Development loop: deploys the built proxy and chosen example mods into the isolated test copy, launches it
    windowed, and prints the lines of spass.log that match a filter.

.DESCRIPTION
    With -WaitForResult the run is a scenario that ends itself (risen.test.finish writes spass\test-result.json): the script
    returns as soon as the file appears, prints the failed checks and sets the exit code (0 = pass, 1 = checks failed,
    2 = no result: stall/timeout/game exited). -Seconds is then only the upper bound.
    A watchdog kills the game when spass.log shows no new line for -StallSeconds or when -Seconds ran out, prints the last
    25 log lines and where the run stopped. Stray Risen.exe processes are killed at the start and at the end (also on
    Ctrl-C or an error). The outcome is left in $global:SpassRun (Reason, Seconds, Result, Timing, Verdict).

.PARAMETER GameDir  Test copy of Risen (default B:\DevDrive\risen-test, or the one of -Instance). Never point this at the real install.
.PARAMETER Instance Parallel test instance 1..n (default 0 = the single main copy, no instance id). Instance 1 is B:\DevDrive\risen-test, n >= 2 is
                    B:\DevDrive\risen-test<n> (created on first use from the main copy: bin copied, data\common and data\compiled junctioned,
                    see docs/DEVELOPMENT.md "Parallel instances"). The layer gets `[debug] instance = "<n>"` (own single-instance mutex), the
                    window is placed at its own offset, and only the Risen.exe of this copy is ever killed.
.PARAMETER Mods     Example mods from <repo>\mods to enable (copied); every other mod in the test copy is disabled
                    by renaming it to <name>.off. "autostart" (starts a new game on the first tick) is kept.
.PARAMETER Seconds  Upper bound of the run (without -WaitForResult: how long the game runs).
.PARAMETER Filter   Regex of log lines to print (default: everything of interest).
.PARAMETER Keep     Do not delete spass.log and saves before the run (to test loading an earlier save).
.PARAMETER KeepModsToml  Do not delete <bin>\spass\mods.toml and <bin>\spass\options before the run (the choices of the mod manager of an earlier run).
.PARAMETER WaitForResult  Scenario mode: [test] enabled = true, return when test-result.json appears.
.PARAMETER StallSeconds   Watchdog: kill the game after this long without a new log line (default 90: loading a new game is quiet for up to ~60 s).
.PARAMETER DeadlineSeconds  [test] deadline_s: the layer itself reports FAIL "timeout" (with the unfinished checks) after this long
                    (default: -Seconds minus 10 with -WaitForResult). Catches a hang inside Lua, which the stall watchdog can only kill.
.PARAMETER Scenario Name written to the result file.
.PARAMETER Param    "key=value" strings for risen.test.param(key).
.PARAMETER Trace    [debug] trace: channels such as "template,balance,save,events,calls,hud" or "all" (see docs/DEVELOPMENT.md).
.PARAMETER TraceScripts  [debug] trace_scripts: script name substrings for the `calls` channel, e.g. "Interact,Loot,Assess".
#>
param(
    [string]$GameDir = '',
    [int]$Instance = 0,
    [string[]]$Mods = @('persistdemo'),
    [int]$Seconds = 300,
    [string]$Filter = 'lua:|save:|load:|session:|world:|\[error\]|\[warn\]|\[test\] (FAIL|finished|deadline)',
    [ValidateSet('trace', 'debug', 'info', 'warn', 'error')][string]$LogLevel = 'info',
    [switch]$Keep,
    # leave the game running after the log was printed (inspect it, then kill Risen.exe yourself)
    [switch]$KeepRunning,
    [switch]$NoAutostart,
    # Lua sandbox off for the run ([lua] unsafe = true): lets a probe mod use io/os (e.g. to write files)
    [switch]$Unsafe,
    # Experiment fixture "modid:relative/path": writes a 16-byte file there inside the deployed mod (e.g. a deliberately corrupt
    # data/common/templates/... file, to see whether the engine reads loose files)
    [string]$CorruptFile = '',
    # "modid=<directory>": copies the directory's contents into the deployed mod (fixtures generated by an earlier probe run)
    [string]$CopyInto = '',
    # [debug] trace_files: log every file the engine opens whose path contains this text, from process start
    [string]$TraceFiles = '',
    # What the "autostart" helper mod does on the first tick: start a new game, or quick-load the last quick save.
    [ValidateSet('new', 'load')][string]$Start = 'new',
    # extra Risen.exe command line switches, e.g. '-noaudio', '-res=640x360' (see docs/DEVELOPMENT.md "Startup time")
    [string[]]$ExtraArgs = @(),
    # client size the game window starts with (written into the copy's ConfigUser.xml before the start, never resized later)
    [string]$WindowSize = '1600x900',
    # voice language the game speaks (ConfigUser.xml <Language VoiceLanguage>): English (default), German, French, Russian; the spoken-line scenarios use it
    [string]$VoiceLanguage = '',
    # text language the game starts with (ConfigUser.xml <Language SubtitleLanguage>, what Settings > Game options > Text language + Apply writes): English by default, so a scenario that switched it
    # never leaks into the next run
    [string]$TextLanguage = 'English',
    [switch]$WaitForResult,
    [int]$StallSeconds = 90,
    [int]$DeadlineSeconds = -1,
    [string]$Scenario = '',
    [string[]]$Param = @(),
    [string]$Trace = '',
    # mods that are deployed but switched off in <bin>\spass\mods.toml (a one-process suite loads them one after the other: risen.mods.load); the file is deleted otherwise
    [string[]]$Disable = @(),
    # keep the player's mods.toml (enabled flags, custom order) of an earlier run: the phase after one that changed it through the mod manager checks what a restart does with it
    [switch]$KeepModsToml,
    # [debug] trace_scripts: substrings (comma separated) of the engine script names the `calls` trace channel reports, e.g. 'Interact,Loot,Assess'
    [string]$TraceScripts = '',
    [switch]$TraceFile,
    # [debug] crash_dump: write a minidump (bin\spass\crash\*.dmp) when the game crashes; 'full' = all memory (1-2 GB), 'off' = only the banner in spass.log / crash.log. docs/DEVELOPMENT.md "Crashes"
    [ValidateSet('off', 'mini', 'full')][string]$CrashDump = 'mini',
    # keep bin\spass\crash.log and the dumps of an earlier run (they are deleted at the start otherwise)
    [switch]$KeepCrash,
    # [debug] engine_guards: 'all' (default), 'findroom' (only the fault guard of FindPortalRoom) or 'none' (the engine as shipped); docs/DEVELOPMENT.md "Crashes"
    [ValidateSet('all', 'findroom', 'none')][string]$EngineGuards = 'all',
    # [debug] race_probe: a thread asks gCSession::GetHud2Location in a tight loop (the rich-presence thread's call, amplified): with -EngineGuards none it reproduces the load crash
    [switch]$RaceProbe,
    # print every check of the result, not only the failed ones
    [switch]$ShowChecks
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$mainCopy = 'B:\DevDrive\risen-test'
if ($GameDir -eq '') { $GameDir = if ($Instance -ge 2) { "$mainCopy$Instance" } else { $mainCopy } }
$GameDir = $GameDir.TrimEnd('\')
if ($GameDir -like 'B:\SteamLibrary*') { throw 'refusing to touch the real install' }

# A further test copy (-Instance n >= 2), made from the main copy: the 60 MB bin directory is copied, data\ini is copied, the big
# data\common and data\compiled stay junctions to the same targets as the main copy's (read by the game, never written), data\extern
# is made below, localappdata is seeded with the main copy's ConfigUser.xml. Delete the directory to drop the copy.
function New-TestCopy([string]$dir, [string]$template) {
    if ($dir -notlike 'B:\DevDrive\risen-test*') { throw "will only create test copies named B:\DevDrive\risen-test*, not $dir" }
    if (-not (Test-Path (Join-Path $template 'bin\Risen.exe'))) { throw "the main test copy $template does not exist" }
    Write-Host "creating the test copy $dir from $template"
    New-Item -ItemType Directory -Force (Join-Path $dir 'data') | Out-Null
    & robocopy (Join-Path $template 'bin') (Join-Path $dir 'bin') /E /XD spass /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
    Copy-Item (Join-Path $template 'data\ini') (Join-Path $dir 'data\ini') -Recurse -Force
    foreach ($j in 'common', 'compiled') {
        $target = @((Get-Item (Join-Path $template "data\$j") -Force).Target)[0]
        if (-not $target -or $target -notlike '*Risen\data\*') { throw "data\$j of the main copy is not a junction into a Risen install ($target)" }
        & cmd.exe /c mklink /J "`"$(Join-Path $dir "data\$j")`"" "`"$target`"" | Out-Null
    }
    $cfgUser = Join-Path $template 'localappdata\Local\Risen\ConfigUser.xml'
    if (Test-Path $cfgUser) {
        New-Item -ItemType Directory -Force (Join-Path $dir 'localappdata\Local\Risen') | Out-Null
        Copy-Item $cfgUser (Join-Path $dir 'localappdata\Local\Risen\ConfigUser.xml')
    }
    $LASTEXITCODE = 0
}
if ($Instance -ge 2 -and -not (Test-Path (Join-Path $GameDir 'bin\Risen.exe'))) { New-TestCopy $GameDir $mainCopy }

$bin = Join-Path $GameDir 'bin'
$modsDir = Join-Path $bin 'spass\mods'
$log = Join-Path $bin 'spass\spass.log'
$resultFile = Join-Path $bin 'spass\test-result.json'
if (-not (Test-Path (Join-Path $bin 'Risen.exe'))) { throw "no Risen.exe in $bin" }

# The test copy plays no intro videos: data\extern is a junction to the real install, so give the copy its own data\externideos
# with an empty logo.ini (what PlayIntros reads). Only the junction itself is removed, never its target.
$externDir = Join-Path $GameDir 'data\extern'
if ((Test-Path $externDir) -and ((Get-Item $externDir -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
    & cmd.exe /c rmdir "`"$externDir`"" | Out-Null
}
if (-not (Test-Path (Join-Path $externDir 'videos\logo.ini'))) {
    New-Item -ItemType Directory -Force (Join-Path $externDir 'videos') | Out-Null
    [IO.File]::WriteAllText((Join-Path $externDir 'videos\logo.ini'), '')
}

# Only the Risen.exe of THIS test copy: other parallel instances (and the real install) are left alone.
function Get-CopyRisen { Get-Process Risen -ErrorAction SilentlyContinue | Where-Object { $_.Path -and $_.Path -like ($bin + '\*') } }
function Stop-Risen {
    Get-CopyRisen | Stop-Process -Force -ErrorAction SilentlyContinue
    Get-CopyRisen | Wait-Process -Timeout 30 -ErrorAction SilentlyContinue
}

# name of a process exit code (NTSTATUS); compared as hex text because PowerShell reads 0xC0000005 as a negative Int32
function Get-ExitName($code) {
    switch ('{0:X8}' -f [uint32]$code) {
        '00000000' { 'normal exit' }
        'C0000005' { 'ACCESS_VIOLATION' }
        'C0000006' { 'IN_PAGE_ERROR' }
        'C000001D' { 'ILLEGAL_INSTRUCTION' }
        'C0000094' { 'INT_DIVIDE_BY_ZERO' }
        'C00000FD' { 'STACK_OVERFLOW' }
        'C0000374' { 'HEAP_CORRUPTION' }
        'C0000409' { 'STACK_BUFFER_OVERRUN / fast fail' }
        'C000013A' { 'CONTROL_C_EXIT' }
        '40010004' { 'DBG_TERMINATE_PROCESS' }
        default    { if ([uint32]$code -ge 3221225472) { 'an NTSTATUS error' } else { 'exit code' } }
    }
}

# seconds of a "[HH:MM:SS.mmm]" log prefix (time of day)
function Get-LogTime([string]$line) {
    if ($line -match '^\[(\d\d):(\d\d):(\d\d)\.(\d+)\]') { return [int]$Matches[1] * 3600 + [int]$Matches[2] * 60 + [int]$Matches[3] + [double]("0." + $Matches[4]) }
    return $null
}

# "where it stopped" for a run that was killed or died without a result
function Show-Stopped($why) {
    Write-Host "---- $why ----" -ForegroundColor Red
    if (-not (Test-Path $log)) { Write-Host 'there is no spass.log: the game never loaded the mod layer'; return }
    $lines = @(Get-Content $log -ErrorAction SilentlyContinue)
    Write-Host '---- last 25 log lines ----'
    $lines | Select-Object -Last 25 | ForEach-Object { Write-Host $_ }
    $text = $lines -join "`n"
    $lastLine = $lines | Select-Object -Last 1
    $lastAt = Get-LogTime $lastLine
    $age = if ($null -ne $lastAt) { [math]::Round(((Get-Date).TimeOfDay.TotalSeconds - $lastAt + 86400) % 86400) } else { '?' }
    $phase = if ($text -notmatch 'game ready: starting Lua runtime') { 'during engine start-up, before the Lua runtime started' }
             elseif ($text -notmatch 'session: start') { 'Lua running, no game session yet (main menu or the first game still loading)' }
             else { 'inside a game session' }
    Write-Host '---- where it stopped ----' -ForegroundColor Red
    Write-Host "phase:             $phase"
    Write-Host "last log line:     $age s before the end: $lastLine"
    foreach ($pair in @(@('last section', '\[test\] section .*'), @('last check', '\[test\] (ok|FAIL) .*'), @('last heartbeat', '\[test\] alive .*'), @('last trace', '\[trace:[^\]]+\] .*'), @('last error', '\[(error|warning)\].*'))) {
        $m = [regex]::Matches($text, '(?m)^\[[^\]]+\] .*?' + $pair[1] + '$')
        if ($m.Count -gt 0) { Write-Host ("{0,-18} {1}" -f ($pair[0] + ':'), $m[$m.Count - 1].Value.Trim()) }
    }
}

$runStart = Get-Date
$global:SpassRun = [pscustomobject]@{ Reason = 'none'; Seconds = 0.0; Total = 0.0; Result = $null; Timing = $null; Verdict = 'none' }
$exitCode = 0
try {
    Stop-Risen
    Copy-Item (Join-Path $repo 'build\RelWithDebInfo\sentry.dll') (Join-Path $bin 'sentry.dll') -Force

    New-Item -ItemType Directory -Force $modsDir | Out-Null
    foreach ($d in Get-ChildItem $modsDir -Directory) {
        if ($d.Name -eq 'autostart' -or $d.Name -like '*.off') { continue }
        Remove-Item ($d.FullName + '.off') -Recurse -Force -ErrorAction SilentlyContinue   # a stale disabled copy
        Rename-Item $d.FullName ($d.Name + '.off')
    }
    foreach ($m in $Mods) {
        $dst = Join-Path $modsDir $m
        Remove-Item "$dst.off" -Recurse -Force -ErrorAction SilentlyContinue
        Remove-Item $dst -Recurse -Force -ErrorAction SilentlyContinue
        Copy-Item (Join-Path $repo "mods\$m") $dst -Recurse
    }
    if ($CorruptFile -ne '') {
        $modId, $rel = $CorruptFile -split ':', 2
        $target = Join-Path (Join-Path $modsDir $modId) $rel
        New-Item -ItemType Directory -Force (Split-Path $target) | Out-Null
        [IO.File]::WriteAllText($target, 'GENOMETP-corrupt')
    }
    if ($CopyInto -ne '') {
        $modId, $srcDir = $CopyInto -split '=', 2
        Copy-Item (Join-Path $srcDir '*') (Join-Path $modsDir $modId) -Recurse -Force
    }
    $auto = Join-Path $modsDir 'autostart'
    Remove-Item "$auto.off" -Recurse -Force -ErrorAction SilentlyContinue
    if ($NoAutostart) {
        Remove-Item $auto -Recurse -Force -ErrorAction SilentlyContinue
    } else {
        New-Item -ItemType Directory -Force $auto | Out-Null
        Set-Content "$auto\mod.toml" "id = `"autostart`"`nname = `"Autostart`"`nversion = `"1.0.0`""
        $call = if ($Start -eq 'load') { 'quick_load' } else { 'new_game' }
        Set-Content "$auto\main.lua" "local done=false`nrisen.on('tick', function() if not done then done=true; risen.log.info('autostart $call -> '..tostring(risen.world.$call())) end end)"
    }
    # Window size: the game starts at this size from its ConfigUser.xml (<Window Right/Bottom>); the window is never resized at
    # runtime (that misaligns the UI and the mouse).
    $cfgUserPath = Join-Path $GameDir 'localappdata\Local\Risen\ConfigUser.xml'
    if ($WindowSize -notmatch '^(\d+)x(\d+)$') { throw "-WindowSize must look like 1600x900, not '$WindowSize'" }
    $winW = $Matches[1]; $winH = $Matches[2]
    if (Test-Path $cfgUserPath) {
        $xml = [System.IO.File]::ReadAllText($cfgUserPath)
        $new = [regex]::Replace($xml, '(?s)(<Window\b[^>]*?)\bBottom="\d+"', "`$1Bottom=`"$winH`"")
        $new = [regex]::Replace($new, '(?s)(<Window\b[^>]*?)\bRight="\d+"', "`$1Right=`"$winW`"")
        # voice language: the element this script adds is replaced/removed on every run, so a run never inherits the language of an earlier one
        $new = [regex]::Replace($new, '(?s)\s*<Language[^>]*VoiceLanguage="[^"]*"[^>]*>\s*</Language>', '')
        if ($VoiceLanguage -ne '') {
            if ($VoiceLanguage -notmatch '^[A-Za-z]+$') { throw "-VoiceLanguage must be a language name such as German, not '$VoiceLanguage'" }
            $new = [regex]::Replace($new, '</Controls>', "</Controls>`n`t`t<Language VoiceLanguage=`"$VoiceLanguage`"></Language>", 1)
        }
        if ($TextLanguage -notmatch '^[A-Za-z]+$') { throw "-TextLanguage must be a language name such as German, not '$TextLanguage'" }
        $new = [regex]::Replace($new, '(SubtitleLanguage=")[^"]*(")', "`${1}$TextLanguage`$2")
        if ($new -ne $xml) { [System.IO.File]::WriteAllText($cfgUserPath, $new) }
    }
    # Isolate the game's %LOCALAPPDATA% (savegames, ConfigUser.xml, screenshots) inside the test copy.
    $appData = (Join-Path $GameDir 'localappdata').Replace('\', '/')
    $cfg = @("log_level = `"$LogLevel`"")
    if ($Unsafe) { $cfg += '[lua]', 'unsafe = true' }
    $cfg += '[debug]', "app_data = `"$appData`""
    if ($Instance -ge 1) { $cfg += "instance = `"$Instance`"" }
    $cfg += "trace_files = `"$TraceFiles`"", "trace = `"$Trace`"", "trace_scripts = `"$TraceScripts`"", "crash_dump = `"$CrashDump`"", "engine_guards = `"$EngineGuards`""
    if ($RaceProbe) { $cfg += 'race_probe = true' }
    if ($TraceFile) { $cfg += 'trace_file = true' }
    if ($WaitForResult) {
        $deadline = if ($DeadlineSeconds -ge 0) { $DeadlineSeconds } else { [math]::Max($Seconds - 10, 10) }
        $cfg += '[test]', 'enabled = true', "deadline_s = $deadline", "scenario = `"$Scenario`""
        if ($Param.Count -gt 0) {
            $cfg += '[test.params]'
            foreach ($kv in $Param) { $k, $v = $kv -split '=', 2; $cfg += ("{0} = `"{1}`"" -f $k.Trim(), $v) }
        }
    }
    Set-Content (Join-Path $bin 'spass\config.toml') $cfg
    $modsToml = Join-Path $bin 'spass\mods.toml'   # the player's choices (risen.mods.enable / disable / set_order): never let an earlier run leak into this one
    # ... and so are the choices of the options menu (spass\options\<mod>.toml)
    if (-not $KeepModsToml) { Remove-Item $modsToml -Force -ErrorAction SilentlyContinue; Remove-Item (Join-Path $bin 'spass\options') -Recurse -Force -ErrorAction SilentlyContinue }
    if ($Disable.Count -gt 0) { Set-Content $modsToml (@('[enabled]') + @($Disable | ForEach-Object { "$_ = false" })) }
    Remove-Item $resultFile -ErrorAction SilentlyContinue
    if (-not $KeepCrash) {
        Remove-Item (Join-Path $bin 'spass\crash.log') -Force -ErrorAction SilentlyContinue
        Remove-Item (Join-Path $bin 'spass\crash') -Recurse -Force -ErrorAction SilentlyContinue
    }
    if (-not $Keep) {
        Remove-Item $log -ErrorAction SilentlyContinue
        Remove-Item (Join-Path $bin 'spass\trace.log') -ErrorAction SilentlyContinue
        Remove-Item (Join-Path $bin 'spass\saves') -Recurse -Force -ErrorAction SilentlyContinue
    }

    $windowed = @{ GameDir = $GameDir; Seconds = $Seconds; KeepRunning = $KeepRunning; StallSeconds = $StallSeconds }
    if ($ExtraArgs.Count -gt 0) { $windowed.ExtraArgs = $ExtraArgs }
    if ($Instance -ge 1) { $windowed.WindowX = 40 * $Instance; $windowed.WindowY = 40 * $Instance }
    if ($WaitForResult) { $windowed.ResultFile = $resultFile }
    & (Join-Path $PSScriptRoot 'run-windowed.ps1') @windowed 6>&1 |
        Select-String -Pattern $Filter | ForEach-Object { $_.Line }
    $launched = $global:SpassRun
    $run = [pscustomobject]@{ Reason = $launched.Reason; Seconds = $launched.Seconds; Total = ((Get-Date) - $runStart).TotalSeconds; Result = $null; Timing = $null; Verdict = 'none'
                              ExitCode = $launched.ExitCode; ExitName = ''; Crashed = $false; Banner = ''; Dumps = @(); Summary = '' }
    $global:SpassRun = $run
    # ---- did the game crash? the exit code of a game that ended by itself, the banner of the crash handler (spass\crash.log), the minidump ----
    $crashLogFile = Join-Path $bin 'spass\crash.log'
    if (Test-Path $crashLogFile) { $run.Banner = (Get-Content $crashLogFile -Raw -ErrorAction SilentlyContinue) }
    $run.Dumps = @(Get-ChildItem (Join-Path $bin 'spass\crash') -Filter *.dmp -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName })
    if ($null -ne $run.ExitCode) { $run.ExitName = Get-ExitName $run.ExitCode }
    $fatalFirstChance = $run.Banner -match 'CRASH \((fatal|UNHANDLED)'
    $run.Crashed = ($launched.Reason -eq 'exited' -and $null -ne $run.ExitCode -and $run.ExitCode -ge 3221225472) -or $fatalFirstChance
    if ($run.Crashed) {
        $head = if ($run.Banner) { ($run.Banner -split "`n" | Where-Object { $_ -match 'CRASH \(' } | Select-Object -First 1) -replace '^\[[^\]]*\] \[fatal\] \[t\d+\] ', '' } else { '' }
        $run.Summary = ("crashed" + $(if ($null -ne $run.ExitCode) { (' (exit code 0x{0:X8} {1})' -f $run.ExitCode, $run.ExitName) } else { '' }) +
                        $(if ($head) { ": $head" } else { ' (no banner: the crash handler did not see it, e.g. a fast fail)' }) +
                        $(if ($run.Dumps.Count -gt 0) { "; dump $($run.Dumps[0])" } else { '' }))
    } elseif ($launched.Reason -eq 'exited' -and $null -ne $run.ExitCode) {
        $run.Summary = ('the game exited by itself with code 0x{0:X8} ({1})' -f $run.ExitCode, $(if ($run.ExitCode -eq 0) { 'a normal quit' } else { $run.ExitName }))
    }
    if ($run.Summary) { Write-Host $run.Summary -ForegroundColor Red }

    # ---- timing from the log: relative to the first line (the mod layer loaded) ----
    $t = [ordered]@{}
    if (Test-Path $log) {
        $lines = @(Get-Content $log -ErrorAction SilentlyContinue)
        $t0 = Get-LogTime ($lines | Select-Object -First 1)
        $rel = { param($rx) $l = $lines | Where-Object { $_ -match $rx } | Select-Object -First 1; if ($l) { $x = Get-LogTime $l; if ($null -ne $x -and $null -ne $t0) { [math]::Round(($x - $t0 + 86400) % 86400, 1) } } }
        $t.lua_started = & $rel 'game ready: starting Lua runtime'
        $t.first_tick = & $rel '\[test\] mark first_tick|autostart (new_game|quick_load)'
        $t.session_start = & $rel 'session: start'
        $t.last_line = if ($lines.Count -gt 0) { $x = Get-LogTime ($lines | Select-Object -Last 1); if ($null -ne $x -and $null -ne $t0) { [math]::Round(($x - $t0 + 86400) % 86400, 1) } }
    }
    $t.result = if ($run.Reason -eq 'result') { [math]::Round($run.Seconds, 1) } else { $null }
    $t.total = [math]::Round($run.Total, 1)
    $run.Timing = $t
    $parts = @()
    if ($null -ne $t.lua_started) { $parts += "lua started $($t.lua_started)" }
    if ($null -ne $t.first_tick) { $parts += "first tick $($t.first_tick)" }
    if ($null -ne $t.session_start) { $parts += "session.start $($t.session_start)" }
    if ($null -ne $t.result) { $parts += "result $($t.result) s after launch" }
    $parts += "run ended by '$($run.Reason)', wall time $($t.total) s"
    Write-Host ('timing (s after the mod layer loaded): ' + ($parts -join ' | '))

    if ($WaitForResult) {
        $result = $null
        if (Test-Path $resultFile) {
            try { $result = Get-Content $resultFile -Raw -Encoding UTF8 | ConvertFrom-Json } catch { Write-Host "result file unreadable: $_" -ForegroundColor Red }
        }
        $run.Result = $result
        if ($null -eq $result) {
            $run.Verdict = 'no result'
            $exitCode = 2
            $why = switch ($run.Reason) {
                'stall'   { "STALL: no new log line for $StallSeconds s, the game was killed" }
                'seconds' { "TIMEOUT: no result within -Seconds $Seconds, the game was killed" }
                'exited'  { if ($run.Summary) { "the game exited without writing a result: $($run.Summary)" } else { 'the game exited without writing a result (crash?)' } }
                default   { "no result ($($run.Reason))" }
            }
            Show-Stopped $why
            if ($run.Banner) { Write-Host '---- crash.log ----' -ForegroundColor Red; Write-Host $run.Banner }
        } else {
            $run.Verdict = $result.status
            Write-Host ("result: {0} '{1}': {2} check(s), {3} failed, {4:N1} s{5}" -f $result.status.ToUpper(), $result.scenario, $result.counts.total, $result.counts.failed, $result.elapsed_s, $(if ($result.reason) { " - " + $result.reason } else { '' }))
            foreach ($c in $result.checks) {
                if ($ShowChecks -or -not $c.ok) {
                    $mark = if ($c.ok) { 'ok  ' } else { 'FAIL' }
                    Write-Host ("  {0} {1}: {2}" -f $mark, $c.name, $c.detail) -ForegroundColor $(if ($c.ok) { 'Gray' } else { 'Red' })
                }
            }
            foreach ($u in $result.unfinished) { Write-Host "  UNFINISHED $u" -ForegroundColor Red }
            if ($result.status -ne 'pass') {
                $exitCode = 1
                if ($result.reason -like 'timeout*' -or $result.unfinished.Count -gt 0) { Show-Stopped "run did not complete: $($result.reason)" }
            }
        }
    } elseif ($run.Reason -eq 'stall') {
        # a scenario without a result file normally ends quietly: the watchdog only cuts the wait short. The caller judges by the log.
        $lastLine = if (Test-Path $log) { Get-Content $log -ErrorAction SilentlyContinue | Select-Object -Last 1 } else { '(no log)' }
        Write-Host "run ended by the stall watchdog (no new log line for $StallSeconds s, the game was killed); last log line: $lastLine"
    }
}
finally {
    if (-not $KeepRunning) { Stop-Risen }
}
exit $exitCode
