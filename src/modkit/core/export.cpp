std::map<std::string, std::string> render_mod(const Project& p) {
    std::map<std::string, std::string> f;
    const ModInfo& m = p.mod;

    std::string toml;
    toml += "# Generated by risen-modkit (the editor's project is modkit/project.json). The next export replaces this file.\n";
    toml += "id          = " + toml_string(m.id) + "\n";
    toml += "name        = " + toml_string(m.name) + "\n";
    toml += "version     = " + toml_string(m.version) + "\n";
    toml += "author      = " + toml_string(m.author) + "\n";
    if (!m.description.empty()) toml += "description = " + toml_string(m.description) + "\n";
    toml += "main        = \"main.lua\"\n";
    toml += "api_version = 1\n";
    if (!m.load_after.empty()) toml += "load_after  = " + toml_list(m.load_after) + "\n";
    if (!m.requires_mods.empty()) toml += "requires    = " + toml_list(m.requires_mods) + "\n";
    // the compiled resources are mounted from assets/ (audio files go to sounds/ and are compiled by the layer when a line uses them)
    const bool resources = std::any_of(p.assets.begin(), p.assets.end(), [](const AssetFile& a) { return !is_raw_audio(a.file); });
    toml += resources ? "assets      = \"assets\"\n" : "assets      = false\n";
    f["mod.toml"] = toml;

    f["main.lua"] = std::string("-- ") + m.name + " " + m.version + ": exported by risen-modkit. Generated: the next export replaces this file, data/, strings/ and modkit/;\n" +
                    "-- hand-written additions go into custom.lua (created once, never overwritten).\n"
                    "local runtime = require(\"modkit.runtime\")\n"
                    "runtime.install({\n"
                    "    balance = require(\"data.balance\"),\n"
                    "    npcs = require(\"data.npcs\"),\n"
                    "    quests = require(\"data.quests\"),\n"
                    "    dialogs = require(\"data.dialogs\"),\n"
                    "    world = require(\"data.world\"),\n"
                    "    assets = require(\"data.assets\"),\n"
                    "})\n"
                    "require(\"custom\")\n";
    f["data/assets.lua"] = data_file("Assets: the image lists of icons the runtime registers (risen.assets.load_icons) before the items that use them are made.",
                                     json::object({{"icons", icon_lists(p)}}));

    f["data/balance.lua"] = data_file("Items, item groups, recipes, NPC and monster templates: a BalanceSpec for risen.balance.install (types/risen.d.lua).",
                                      balance_spec(p));
    f["data/npcs.lua"] = data_file("Placed NPCs: risen.npc.persistent declarations (spawned in a new game, restored after a load, never twice).", npcs_data(p));
    f["data/quests.lua"] = data_file("Quests: risen.quest.define, made on load.before and on every session.start (before the dialogues that name them).", quests_data(p));
    {
        json actions = json::array();
        json infos = dialogs_data(p, &actions);
        // one script per quest action, however many lines call it
        json unique = json::array();
        std::set<std::string> seen;
        for (auto& a : actions)
            if (seen.insert(a["script"].get<std::string>()).second) unique.push_back(a);
        json dialogs = json::object();
        dialogs["infos"] = infos;
        dialogs["quest_actions"] = unique;
        f["data/dialogs.lua"] = data_file("Dialogue options: risen.dialog.create in this order (parents first), on load.before and on every session.start; the quest actions their lines call.", dialogs);
    }
    f["data/world.lua"] = data_file("World edits: entities spawned and items put into containers once per savegame (on world.ready; risen.save remembers what was done); entities of the world removed or moved (by id, on every world.ready).", world_data(p));
    f["modkit/runtime.lua"] = runtime_lua();
    f["modkit/project.json"] = dump_project(p);

    // strings: the first language is the fallback for every language (all.csv), the others get their own file
    const auto rows = string_rows(p);
    if (!rows.empty() && !m.languages.empty()) {
        const std::string& first = m.languages.front();
        auto table = [&](const std::string& lang, bool fallback) {
            std::string s = "# Generated by risen-modkit. One id;\"text\" per line.\nid;text\n";
            size_t n = 0;
            for (auto& [id, t] : rows) {
                auto it = t.find(lang);
                if (it == t.end() && fallback && !t.empty()) it = t.begin();
                if (it == t.end()) continue;
                s += id + ";" + csv_field(it->second) + "\n";
                ++n;
            }
            return n ? s : std::string();
        };
        if (std::string s = table(first, true); !s.empty()) f["strings/all.csv"] = s;
        for (size_t i = 1; i < m.languages.size(); ++i)
            if (std::string s = table(m.languages[i], false); !s.empty()) f["strings/" + m.languages[i] + ".csv"] = s;
    }
    return f;
}

ExportResult export_mod(const Project& p, const std::string& out_dir, const ExportOptions& opts) {
    ExportResult r;
    const fs::path out = u8(out_dir);
    std::error_code ec;
    if (out_dir.empty()) {
        r.errors.push_back("no export folder");
        return r;
    }
    if (!opts.game_data_dir.empty() && path_within(out, u8(opts.game_data_dir))) {
        r.errors.push_back("the export folder is inside the game's data folder; export into <Risen>\\bin\\spass\\mods\\<id> instead");
        return r;
    }
    if (fs::exists(out, ec)) {
        if (!fs::is_directory(out, ec)) {
            r.errors.push_back(out_dir + " is a file");
            return r;
        }
        const bool ours = fs::exists(out / "modkit" / "project.json", ec);
        const bool empty = fs::directory_iterator(out, ec) == fs::directory_iterator();
        if (!ours && !empty && !opts.allow_foreign) {
            r.errors.push_back(out_dir + " holds files that risen-modkit did not write (no modkit/project.json): choose an empty or new folder");
            return r;
        }
    }
    const auto files = render_mod(p);
    try {
        for (auto& [rel, content] : files) {
            if (write_text_if_changed(out / u8(rel), content)) r.written.push_back(rel);
            else r.unchanged.push_back(rel);
        }
        if (!fs::exists(out / "custom.lua", ec)) {
            write_text(out / "custom.lua", "-- custom.lua: hand-written additions to the mod. risen-modkit creates this file once and never overwrites it.\n"
                                           "-- Everything of the layer's API is available (types/risen.d.lua, docs/MODDING_GUIDE.md); the exported content is\n"
                                           "-- installed before this file runs.\n");
            r.written.push_back("custom.lua");
        }
        // stale generated files: data/*.lua and strings/*.csv the export does not produce any more
        for (const char* dir : {"data", "strings"}) {
            const fs::path d = out / dir;
            if (!fs::is_directory(d, ec)) continue;
            for (auto it = fs::directory_iterator(d, ec); !ec && it != fs::directory_iterator(); it.increment(ec)) {
                const std::string rel = std::string(dir) + "/" + u8str(it->path().filename());
                if (it->is_regular_file() && !files.count(rel)) {
                    fs::remove(it->path(), ec);
                    r.removed.push_back(rel);
                }
            }
        }
        // asset files: compiled resources copied flat into assets/ (mounted by the layer), audio files into sounds/ (the voiced lines name them);
        // stale ones removed
        std::set<std::string> produced;  // "assets/x", "sounds/y"
        const fs::path base = opts.project_dir.empty() ? fs::current_path() : u8(opts.project_dir);
        auto put = [&](const std::string& rel, const std::string& content) {
            produced.insert(rel);
            if (write_text_if_changed(out / u8(rel), content)) r.written.push_back(rel);
            else r.unchanged.push_back(rel);
        };
        // pictures: an icon goes into the atlas, every other one becomes a texture <stem>._ximg (a new one, or a game texture replaced)
        const auto icon_names = icon_pictures(p);
        std::vector<std::pair<std::string, Picture>> icons;
        for (auto& a : p.assets) {
            const fs::path src = u8(a.file).is_absolute() ? u8(a.file) : base / u8(a.file);
            const std::string name = u8str(src.filename());
            if (!is_picture(name)) continue;
            std::string why;
            std::optional<Picture> pic;
            try {
                pic = load_picture(read_text(src), why);
            } catch (const std::exception& e) {
                why = e.what();
            }
            if (!pic) {
                r.errors.push_back("picture " + name + ": " + why);
                continue;
            }
            if (std::find(icon_names.begin(), icon_names.end(), p2m::lower(name)) != icon_names.end())
                icons.push_back({project_icon_name(p.mod.id, name), *pic});
            else
                put("assets/" + picture_compiled_name(name), build_ximg(*pic, XimgKind::Texture, u8str(src.extension())));
        }
        if (!icons.empty()) {
            std::sort(icons.begin(), icons.end(), [](const auto& a, const auto& b) { return a.first < b.first; });
            const IconAtlas atlas = build_icon_atlas(icons, p.mod.id + "_IconAtlas.dds");
            put("assets/" + p.mod.id + "_IconAtlas._ximg", build_ximg(atlas.texture, XimgKind::Gui));
            put("assets/" + p.mod.id + "_Icons.ximl", atlas.ximl);
        }
        for (auto& a : p.assets) {
            const fs::path src = u8(a.file).is_absolute() ? u8(a.file) : base / u8(a.file);
            const std::string name = u8str(src.filename());
            if (is_picture(name)) continue;
            const std::string rel = (is_raw_audio(name) ? "sounds/" : "assets/") + name;
            produced.insert(rel);
            const fs::path dst = out / u8(rel);
            if (!fs::exists(src, ec)) {
                r.errors.push_back("asset file missing: " + u8str(src));
                continue;
            }
            fs::create_directories(dst.parent_path(), ec);
            const bool same = fs::exists(dst, ec) && fs::file_size(dst, ec) == fs::file_size(src, ec) && read_text(dst) == read_text(src);
            if (same) {
                r.unchanged.push_back(rel);
            } else {
                fs::copy_file(src, dst, fs::copy_options::overwrite_existing, ec);
                if (ec) r.errors.push_back("cannot copy " + u8str(src) + ": " + ec.message());
                else r.written.push_back(rel);
            }
        }
        // compiled sounds the lines use (the game's or the project's): the audio inside, as sounds/<name>.mp3 (core/assets.h)
        for (const std::string& ref : dialog_sound_refs(p)) {
            if (!is_compiled_sound(ref)) continue;
            std::string bytes;
            try {
                if (const AssetFile* a = find_asset(p, ref)) {
                    const fs::path src = u8(a->file).is_absolute() ? u8(a->file) : base / u8(a->file);
                    bytes = read_text(src);
                } else if (opts.game) {
                    bytes = opts.game->read(ref);
                } else {
                    r.errors.push_back("the game sound " + ref + " needs the game data (Settings) to be exported");
                    continue;
                }
            } catch (const std::exception& e) {
                r.errors.push_back("sound " + ref + ": " + e.what());
                continue;
            }
            std::string why;
            const auto snd = open_sound(bytes, why);
            if (!snd) {
                r.errors.push_back("sound " + ref + ": " + why);
                continue;
            }
            put(sound_export_path(ref), snd->audio);
        }
        for (const char* dir : {"assets", "sounds"}) {
            if (!fs::is_directory(out / dir, ec)) continue;
            for (auto it = fs::directory_iterator(out / dir, ec); !ec && it != fs::directory_iterator(); it.increment(ec)) {
                const std::string rel = std::string(dir) + "/" + u8str(it->path().filename());
                if (it->is_regular_file() && !produced.count(rel)) {
                    fs::remove(it->path(), ec);
                    r.removed.push_back(rel);
                }
            }
        }
    } catch (const std::exception& e) {
        r.errors.push_back(e.what());
    }
    r.ok = r.errors.empty();
    return r;
}

