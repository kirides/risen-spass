json balance_spec(const Project& p) {
    json spec = json::object();
    // shipped items: sorted by name
    std::vector<const ItemDef*> edits, news;
    for (auto& it : p.items) (it.mode == Mode::Edit ? edits : news).push_back(&it);
    auto by_name = [](const ItemDef* a, const ItemDef* b) { return a->name < b->name; };
    std::sort(edits.begin(), edits.end(), by_name);
    std::sort(news.begin(), news.end(), by_name);
    if (!edits.empty()) {
        json items = json::object();
        for (const ItemDef* it : edits) {
            json e = json::object();
            put(e, "value", it->value);
            put(e, "damage", it->damage);
            put(e, "mana_cost", it->mana_cost);
            if (it->requirements) e["requires"] = requirement_json(*it);
            if (it->modifies) e["modifies"] = modifier_json(*it);
            put(e, "use_type", it->use_type);
            put(e, "category", it->category);
            // a shipped item's mesh, icon and material are plain properties (the named settings exist only for new templates)
            PropEdits props = it->properties;
            if (it->mesh) props["eCMesh_PS"]["MeshFileName"] = *it->mesh;
            if (it->icon) props["gCItem_PS"]["IconImage"] = resolve_icon(p, *it->icon);
            if (it->material) props["eCMesh_PS"]["MaterialSwitch"] = *it->material;
            if (json pj = props_json(props); !pj.empty()) e["properties"] = pj;
            items[it->name] = e;
        }
        spec["items"] = items;
    }
    if (!p.item_groups.empty()) {
        json groups = json::array();
        for (auto& g : p.item_groups) {
            json e = json::object();
            if (!g.group.empty()) e["group"] = g.group;
            if (!g.match.empty()) e["match"] = g.match;
            if (!g.exclude.empty()) e["exclude"] = g.exclude;
            if (!g.names.empty()) e["names"] = g.names;
            put(e, "value_mult", g.value_mult);
            put(e, "damage_mult", g.damage_mult);
            groups.push_back(e);
        }
        spec["item_groups"] = groups;
    }
    if (!news.empty()) {
        json items = json::object();
        for (const ItemDef* it : news) {
            json e = json::object();
            e["base"] = it->base;
            if (json t = text_value(it->label, p.mod.languages); !t.is_null()) e["name"] = t;
            if (json t = text_value(it->description, p.mod.languages); !t.is_null()) e["description"] = t;
            put(e, "value", it->value);
            put(e, "damage", it->damage);
            put(e, "mana_cost", it->mana_cost);
            if (it->requirements) e["requires"] = requirement_json(*it);
            if (it->modifies) e["modifies"] = modifier_json(*it);
            put(e, "use_type", it->use_type);
            put(e, "category", it->category);
            put(e, "mesh", it->mesh);
            if (it->icon) e["icon"] = resolve_icon(p, *it->icon);
            put(e, "material", it->material);
            if (json pj = props_json(it->properties); !pj.empty()) e["properties"] = pj;
            items[it->name] = e;
        }
        spec["new_items"] = items;
    }

    std::vector<const RecipeDef*> redits, rnews;
    for (auto& r : p.recipes) (r.mode == Mode::Edit ? redits : rnews).push_back(&r);
    auto rby_name = [](const RecipeDef* a, const RecipeDef* b) { return a->name < b->name; };
    std::sort(redits.begin(), redits.end(), rby_name);
    std::sort(rnews.begin(), rnews.end(), rby_name);
    if (!redits.empty()) {
        json recipes = json::object();
        for (const RecipeDef* r : redits) {
            json e = json::object();
            if (!r->station.empty()) e["station"] = r->station;
            if (r->ingredients) e["ingredients"] = ingredients(*r->ingredients);
            if (r->skills) e["skills"] = int_map(*r->skills);
            put(e, "result", r->result);
            PropEdits props = r->properties;
            if (r->icon) props["gCItem_PS"]["IconImage"] = resolve_icon(p, *r->icon);
            if (r->mesh) props["eCMesh_PS"]["MeshFileName"] = *r->mesh;
            if (r->value) props["gCItem_PS"]["GoldValue"] = *r->value;
            if (json pj = props_json(props); !pj.empty()) e["properties"] = pj;
            recipes[r->name] = e;
        }
        spec["recipes"] = recipes;
    }
    if (!rnews.empty()) {
        json recipes = json::object();
        for (const RecipeDef* r : rnews) {
            json e = json::object();
            if (!r->base.empty()) e["base"] = r->base;
            if (json t = text_value(r->label, p.mod.languages); !t.is_null()) e["name"] = t;
            if (json t = text_value(r->description, p.mod.languages); !t.is_null()) e["description"] = t;
            e["station"] = r->station;
            e["ingredients"] = ingredients(r->ingredients.value_or(std::vector<Ingredient>{}));
            e["result"] = r->result.value_or(std::string());
            if (r->skills) e["skills"] = int_map(*r->skills);
            if (r->icon) e["icon"] = resolve_icon(p, *r->icon);
            put(e, "mesh", r->mesh);
            put(e, "value", r->value);
            if (json pj = props_json(r->properties); !pj.empty()) e["properties"] = pj;
            if (r->learn) e["learn"] = true;
            recipes[r->name] = e;
        }
        spec["new_recipes"] = recipes;
    }

    std::vector<const NpcTemplateDef*> nedits, nnews;
    for (auto& n : p.npc_templates) (n.mode == Mode::Edit ? nedits : nnews).push_back(&n);
    auto nby_name = [](const NpcTemplateDef* a, const NpcTemplateDef* b) { return a->name < b->name; };
    std::sort(nedits.begin(), nedits.end(), nby_name);
    std::sort(nnews.begin(), nnews.end(), nby_name);
    auto npc_entry = [&](const NpcTemplateDef& n, bool fresh) {
        json e = json::object();
        if (fresh) {
            e["base"] = n.base;
            if (json t = text_value(n.label, p.mod.languages); !t.is_null()) e["name"] = t;
            put(e, "mesh", n.mesh);
        }
        put(e, "hp_max", n.hp_max);
        put(e, "hp", n.hp);
        put(e, "hp_mult", n.hp_mult);
        put(e, "mana_max", n.mana_max);
        put(e, "mana", n.mana);
        put(e, "mana_mult", n.mana_mult);
        put(e, "level", n.level);
        put(e, "level_add", n.level_add);
        put(e, "level_mult", n.level_mult);
        put(e, "xp", n.xp);
        put(e, "damage", n.damage);
        put(e, "damage_mult", n.damage_mult);
        put(e, "damage_type", n.damage_type);
        if (n.skills) e["skills"] = int_map(*n.skills);
        put(e, "guild", n.guild);
        put(e, "species", n.species);
        put(e, "attitude", n.attitude);
        put(e, "bravery", n.bravery);
        put(e, "damage_calc", n.damage_calc);
        put(e, "combat_species", n.combat_species);
        put(e, "ai_group", n.ai_group);
        if (n.loot) e["loot"] = int_map(*n.loot);
        PropEdits props = n.properties;
        if (!fresh && n.mesh) props["eCAnimation_PS"]["ResourceFilePath"] = *n.mesh;
        if (json pj = props_json(props); !pj.empty()) e["properties"] = pj;
        return e;
    };
    if (!nedits.empty()) {
        json npcs = json::object();
        for (const NpcTemplateDef* n : nedits) npcs[n->name] = npc_entry(*n, false);
        spec["npcs"] = npcs;
    }
    if (!nnews.empty()) {
        json npcs = json::object();
        for (const NpcTemplateDef* n : nnews) npcs[n->name] = npc_entry(*n, true);
        spec["new_npcs"] = npcs;
    }
    // spells (the Spells panel): `spells` edits shipped ones, `new_spells` makes new ones of their pieces
    auto spell_entry = [&](const SpellDef& s, bool fresh) {
        json e = json::object();
        if (fresh) {
            e["base"] = s.base;
            if (!s.forms.empty()) e["forms"] = s.forms;
            if (json t = text_value(s.label, p.mod.languages); !t.is_null()) e["name"] = t;
            if (json t = text_value(s.description, p.mod.languages); !t.is_null()) e["description"] = t;
            if (s.icon) e["icon"] = resolve_icon(p, *s.icon);
            put(e, "value", s.value);
        }
        put(e, "mana_cost", s.mana_cost);
        put(e, "mana_mult", s.mana_mult);
        put(e, "scroll_mana_cost", s.scroll_mana_cost);
        put(e, "orb_mana_cost", s.orb_mana_cost);
        if (s.requirements) e["requires"] = int_map(*s.requirements);
        put(e, "consume", s.consume);
        if (!s.damage.is_null()) e["damage"] = s.damage;
        put(e, "damage_mult", s.damage_mult);
        put(e, "damage_type", s.damage_type);
        put(e, "speed", s.speed);
        put(e, "speed_mult", s.speed_mult);
        put(e, "radius", s.radius);
        put(e, "radius_mult", s.radius_mult);
        put(e, "effect", s.effect);
        if (json pj = props_json(s.properties); !pj.empty()) e["properties"] = pj;
        if (s.extra.is_object())
            for (auto& [k, v] : s.extra.items())
                if (!e.contains(k)) e[k] = v;
        return e;
    };
    {
        std::vector<const SpellDef*> sedits, snews;
        for (auto& s : p.spells) (s.mode == Mode::Edit ? sedits : snews).push_back(&s);
        auto sby_name = [](const SpellDef* a, const SpellDef* b) { return a->name < b->name; };
        std::sort(sedits.begin(), sedits.end(), sby_name);
        std::sort(snews.begin(), snews.end(), sby_name);
        if (!sedits.empty()) {
            json spells = json::object();
            for (const SpellDef* s : sedits) spells[s->name] = spell_entry(*s, false);
            spec["spells"] = spells;
        }
        if (!snews.empty()) {
            json spells = json::object();
            for (const SpellDef* s : snews) spells[s->name] = spell_entry(*s, true);
            spec["new_spells"] = spells;
        }
    }
    if (!p.npc_groups.empty()) {
        json groups = json::array();
        for (auto& g : p.npc_groups) {
            json e = json::object();
            if (!g.group.empty()) e["group"] = g.group;
            if (!g.match.empty()) e["match"] = g.match;
            if (!g.exclude.empty()) e["exclude"] = g.exclude;
            if (!g.names.empty()) e["names"] = g.names;
            put(e, "hp_mult", g.hp_mult);
            put(e, "mana_mult", g.mana_mult);
            put(e, "level_mult", g.level_mult);
            put(e, "level_add", g.level_add);
            put(e, "xp_mult", g.xp_mult);
            put(e, "damage_mult", g.damage_mult);
            if (g.skills_mult) e["skills_mult"] = *g.skills_mult;
            if (g.skills_add) e["skills_add"] = int_map(*g.skills_add);
            put(e, "guild", g.guild);
            put(e, "species", g.species);
            put(e, "attitude", g.attitude);
            put(e, "bravery", g.bravery);
            put(e, "damage_calc", g.damage_calc);
            put(e, "ai_group", g.ai_group);
            if (g.extra.is_object())
                for (auto& [k, v] : g.extra.items())
                    if (!e.contains(k)) e[k] = v;
            groups.push_back(e);
        }
        spec["npc_groups"] = groups;
    }
    // sections without a panel (kept from an imported mod), after the editor's own
    for (auto& [k, v] : p.extra_balance.items())
        if (!spec.contains(k)) spec[k] = v;
    return spec;
}

json quests_data(const Project& p) {
    json list = json::array();
    for (auto& q : p.quests) {
        json e = json::object();
        e["name"] = q.name;
        // risen.quest.define takes one title: the first language's
        for (auto& lang : p.mod.languages)
            if (auto it = q.title.find(lang); it != q.title.end() && !it->second.empty()) {
                e["title"] = it->second;
                break;
            }
        if (!e.contains("title") && !q.title.empty()) e["title"] = q.title.begin()->second;
        e["type"] = q.type;
        put(e, "xp", q.xp);
        if (q.silent) e["silent"] = true;
        std::vector<DialogIssue> issues;
        json flow = compile_quest(p, q, issues);
        if (!flow.is_null()) e["flow"] = flow;
        list.push_back(e);
    }
    return list;
}

json world_data(const Project& p) {
    json spawns = json::array(), containers = json::array();
    for (auto& s : p.world.spawns) {
        json e = json::object();
        e["key"] = s.uid.substr(0, 12);  // the key of "already done" in risen.save: stable across renames
        e["template"] = s.template_name;
        e["position"] = json::array({s.position[0], s.position[1], s.position[2]});
        if (s.rotation[0] != 0 || s.rotation[1] != 0 || s.rotation[2] != 0) e["rotation"] = json::array({s.rotation[0], s.rotation[1], s.rotation[2]});
        if (s.amount != 1) e["amount"] = s.amount;
        e["world"] = world_of(p, s.world);  // the runtime applies it only while this world is active
        if (const LayerDef* l = layer_of_spawn(p, s.uid)) e["layer"] = l->name;
        spawns.push_back(e);
    }
    // entities of the world removed or moved: by their ID, applied on every world.ready (Entity:kill / Entity:set_pose)
    json removals = json::array(), moves = json::array();
    for (auto& r : p.world.removals) {
        json e = json::object();
        e["key"] = r.uid.substr(0, 12);
        e["id"] = r.guid;
        if (!r.entity_name.empty()) e["name"] = r.entity_name;
        e["world"] = world_of(p, r.world);
        removals.push_back(e);
    }
    for (auto& m : p.world.moves) {
        json e = json::object();
        e["key"] = m.uid.substr(0, 12);
        e["id"] = m.guid;
        if (!m.entity_name.empty()) e["name"] = m.entity_name;
        if (m.position) e["position"] = json::array({(*m.position)[0], (*m.position)[1], (*m.position)[2]});
        if (m.rotation) e["rotation"] = json::array({(*m.rotation)[0], (*m.rotation)[1], (*m.rotation)[2]});
        e["world"] = world_of(p, m.world);
        moves.push_back(e);
    }
    for (auto& c : p.world.containers) {
        json e = json::object();
        e["key"] = c.uid.substr(0, 12);
        e["id"] = c.guid;
        if (!c.entity_name.empty()) e["name"] = c.entity_name;
        json items = json::array(), equip = json::array();
        for (auto& i : c.items) {
            items.push_back(json::array({i.item, i.amount}));
            if (i.equip) equip.push_back(i.item);  // an NPC's inventory: what he wears or holds (the runtime equips it after giving it)
        }
        e["items"] = items;
        if (!equip.empty()) e["equip"] = equip;
        e["world"] = world_of(p, c.world);
        if (const LayerDef* l = layer_of_container(p, c.uid)) e["layer"] = l->name;
        containers.push_back(e);
    }
    json w = json::object();
    w["spawns"] = spawns;
    w["containers"] = containers;
    if (!removals.empty()) w["removals"] = removals;
    if (!moves.empty()) w["moves"] = moves;
    // teaching limits of placed NPCs: applied on every world.ready (risen.npc.set_teach_limit writes into the entity, idempotent)
    json teachers = json::array();
    for (auto& t : p.teachers) {
        json e = json::object();
        e["id"] = t.guid;
        if (!t.entity_name.empty()) e["name"] = t.entity_name;
        e["skill"] = t.skill;
        e["max"] = t.max;
        e["world"] = world_of(p, t.world);
        teachers.push_back(e);
    }
    if (!teachers.empty()) w["teachers"] = teachers;
    return w;
}

json patches_data(const Project& p) {
    json list = json::array();
    for (auto& x : p.patches) {
        json e = json::object();
        e["template"] = x.template_name;
        if (json pj = props_json(x.properties); !pj.empty()) e["properties"] = pj;
        list.push_back(e);
    }
    return list;
}

json dialog_edits_data(const Project& p) {
    json list = json::array();
    for (auto& x : p.dialog_edits) {
        json e = json::object();
        e["info"] = x.info;
        put(e, "xp_add", x.xp_add);
        put(e, "xp_old", x.xp_old);
        put(e, "xp_new", x.xp_new);
        put(e, "chapter", x.chapter);
        json refills = json::array();
        for (auto& r : x.refills) refills.push_back(json{{"trader", r.trader}, {"item", r.item}, {"count", r.count}});
        if (!refills.empty()) e["refills"] = refills;
        json ops = json::array();
        for (auto& op : x.ops) {
            json o = json::object();
            o["kind"] = op.kind;
            if (op.index) o["index"] = op.index;
            if (!op.cls.empty()) o["class"] = op.cls;
            o["name"] = op.name;
            if (!op.old_value.empty() || op.kind != "add_condition") o["old"] = op.old_value;
            o["new"] = op.new_value;
            ops.push_back(o);
        }
        if (!ops.empty()) e["ops"] = ops;
        list.push_back(e);
    }
    return list;
}

