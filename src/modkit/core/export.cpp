constexpr const char* kGeneratedNote =
    "-- Generated by risen-modkit from the project in modkit/project.json. The next export replaces this file: put hand-written code into custom.lua.\n";

std::string toml_string(const std::string& s) {
    std::string o = "\"";
    for (unsigned char c : s) {
        switch (c) {
            case '"': o += "\\\""; break;
            case '\\': o += "\\\\"; break;
            case '\n': o += "\\n"; break;
            case '\r': o += "\\r"; break;
            case '\t': o += "\\t"; break;
            default:
                if (c < 0x20) {
                    char buf[8];
                    std::snprintf(buf, sizeof buf, "\\u%04x", c);
                    o += buf;
                } else {
                    o += static_cast<char>(c);
                }
        }
    }
    return o + "\"";
}

std::string toml_list(const std::vector<std::string>& v) {
    std::string o = "[";
    for (size_t i = 0; i < v.size(); ++i) o += (i ? ", " : "") + toml_string(v[i]);
    return o + "]";
}

std::string csv_field(const std::string& s) { return "\"" + p2m::replace_all(s, "\"", "\"\"") + "\""; }

// a text per language for the layer: one string when the project has one language, else { English = ..., German = ... }
json text_value(const Text& t, const std::vector<std::string>& languages) {
    if (t.empty()) return nullptr;
    if (languages.size() <= 1 || t.size() == 1) {
        const std::string first = languages.empty() ? std::string() : languages.front();
        auto it = t.find(first);
        return it != t.end() ? json(it->second) : json(t.begin()->second);
    }
    json o = json::object();
    for (auto& l : languages)
        if (auto it = t.find(l); it != t.end()) o[l] = it->second;
    for (auto& [l, s] : t)
        if (!o.contains(l)) o[l] = s;
    return o;
}

json props_json(const PropEdits& p) {
    json o = json::object();
    for (auto& [set, list] : p) {
        if (list.empty()) continue;
        json s = json::object();
        for (auto& [k, v] : list) s[k] = v;
        o[set] = s;
    }
    return o;
}

template <class T>
void put(json& o, const char* k, const std::optional<T>& v) {
    if (v) o[k] = *v;
}

json int_map(const IntMap& m) {
    json o = json::object();
    for (auto& [k, v] : m) o[k] = v;
    return o;
}

// ingredients as a list (keeps the order the modder chose): { { item = "It_IronOre", count = 2 }, ... }
json ingredients(const std::vector<Ingredient>& v) {
    json a = json::array();
    for (auto& i : v) {
        json e = json::object();
        e["item"] = i.item;
        e["count"] = i.count;
        a.push_back(e);
    }
    return a;
}

