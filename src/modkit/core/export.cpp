// texts that are not part of a template spec: labels and descriptions of shipped templates the project renames
std::map<std::string, Text> string_rows(const Project& p) {
    std::map<std::string, Text> rows;
    for (auto& it : p.items) {
        if (it.mode != Mode::Edit) continue;
        if (!it.label.empty()) rows["FO_" + it.name] = it.label;
        if (!it.description.empty()) rows["ITEMDESC_" + it.name] = it.description;
    }
    for (auto& r : p.recipes) {
        if (r.mode != Mode::Edit) continue;
        if (!r.label.empty()) rows["FO_" + r.name] = r.label;
        if (!r.description.empty()) rows["ITEMDESC_" + r.name] = r.description;
    }
    for (auto& n : p.npc_templates)
        if (n.mode == Mode::Edit && !n.label.empty()) rows["FO_" + n.name] = n.label;
    // a placed NPC's label is the text of FO_<unique name> (risen.npc.persistent's `label` sets one text for every language)
    for (auto& n : p.npcs)
        if (!n.label.empty()) rows["FO_" + n.name] = n.label;
    return rows;
}

